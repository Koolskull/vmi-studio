//! Pixel icons for the tool grid. Sixteen rows of sixteen cells, `#` is ink.
//! They scale by whole pixels so a cell stays crisp at any grid size.

use vmi_core::Tool;

pub const SIDE: usize = 16;

pub type Icon = [&'static str; SIDE];

pub fn icon(tool: Tool) -> &'static Icon {
    match tool {
        Tool::Pen => &PEN,
        Tool::Pencil => &PENCIL,
        Tool::Charcoal => &CHARCOAL,
        Tool::Paint => &PAINT,
        Tool::Air => &AIR,
        Tool::Eraser => &ERASER,
        Tool::Smudge => &SMUDGE,
        Tool::Blend => &BLEND,
        Tool::Fill => &FILL,
        Tool::Dither => &DITHER,
        Tool::Line => &LINE,
        Tool::Vector => &VECTOR,
        Tool::Curve => &CURVE,
        Tool::Point => &POINT,
        Tool::Bone => &BONE,
        Tool::Grain => &GRAIN,
        Tool::WarpTarget => &WARP_TARGET,
        Tool::WarpMask => &WARP_MASK,
        Tool::Select => &SELECT,
        Tool::Dropper => &DROPPER,
        Tool::CutRect => &CUT_RECT,
        Tool::CutLasso => &CUT_LASSO,
        Tool::CutPolygon => &CUT_POLYGON,
    }
}

/// Every lit cell of an icon as `(column, row)`.
pub fn cells(icon: &Icon) -> impl Iterator<Item = (usize, usize)> + '_ {
    icon.iter().enumerate().flat_map(|(row, line)| {
        line.bytes()
            .enumerate()
            .filter(|(_, b)| *b == b'#')
            .map(move |(col, _)| (col, row))
    })
}


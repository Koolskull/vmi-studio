#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_tool_has_a_square_icon_with_some_ink() {
        for tool in Tool::PALETTE {
            let icon = icon(*tool);
            for row in icon.iter() {
                assert_eq!(row.len(), SIDE, "{tool:?}");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "{tool:?}");
            }
            assert!(cells(icon).count() >= 12, "{tool:?}");
        }
    }
}
